"""
Strategy manager orchestrator.
Coordinates regime adaptation, signal generation, and portfolio allocation.
"""

from datetime import UTC, datetime
from pathlib import Path

from loguru import logger

from src.models.schemas import PredictionResult
from src.strategy.portfolio_allocator import PortfolioAllocator
from src.strategy.regime_adapter import RegimeAdapter
from src.strategy.schemas import SignalDirection, StrategyConfig, TradingSignal
from src.strategy.signal_generator import SignalGenerator
from src.utils.config import get_settings

# Default location for per-asset thresholds produced by batch_oos_scorecard.py
_DEFAULT_THRESHOLDS_PATH = (
    Path(__file__).resolve().parent.parent.parent / "data" / "config" / "optimal_thresholds.json"
)


class StrategyManager:
    """
    Orchestrates the strategy pipeline:
    prediction -> regime adaptation -> signal generation.
    """

    def __init__(
        self,
        configs: dict[str, StrategyConfig] | None = None,
        excluded_epics: set[str] | None = None,
        scalp_mode: bool = False,
        orb_fvg_epics: set[str] | None = None,
        ml_primary_enabled: bool = False,
    ):
        """
        Initialize strategy manager.

        Args:
            configs: Per-asset strategy configs. Uses defaults if None.
            excluded_epics: Epics to skip (decision=EXCLUDE from scorecard).
            scalp_mode: If True, use ScalpScoreStrategy as primary signal source.
            orb_fvg_epics: Epics to use ORB+FVG strategy (default: {"US500"}).
            ml_primary_enabled: If True, ML decides direction, ScalpScore confirms quality.
        """
        self._configs = configs or {}
        self.excluded_epics: set[str] = excluded_epics or set()
        self.scalp_mode = scalp_mode
        self._ml_primary_enabled = ml_primary_enabled
        self._scalp_strategy = None
        self._orb_fvg_strategy = None
        self.orb_fvg_epics: set[str] = orb_fvg_epics if orb_fvg_epics is not None else {"US500"}
        if scalp_mode or ml_primary_enabled:
            from src.strategy.scalp_score_strategy import ScalpScoreStrategy

            self._scalp_strategy = ScalpScoreStrategy()
        if self.orb_fvg_epics:
            from src.strategy.orb_fvg_strategy import OrbFvgStrategy

            self._orb_fvg_strategy = OrbFvgStrategy()

    @classmethod
    def from_optimal_thresholds(
        cls,
        path: Path | None = None,
    ) -> "StrategyManager":
        """
        Create StrategyManager with per-asset confidence thresholds
        from the optimal_thresholds.json generated by batch_oos_scorecard.py.

        If the file doesn't exist, falls back to default config.
        """
        from src.backtest.scorecard import load_optimal_thresholds

        thresholds_path = path or _DEFAULT_THRESHOLDS_PATH
        data = load_optimal_thresholds(thresholds_path)

        if data is None:
            logger.info("No optimal_thresholds.json found, using default configs")
            return cls()

        per_asset = data.get("per_asset", {})
        default_conf = data.get("default_confidence", 0.40)
        configs: dict[str, StrategyConfig] = {}
        excluded: set[str] = set()

        for epic, info in per_asset.items():
            decision = info.get("decision", "KEEP")
            if decision == "EXCLUDE":
                excluded.add(epic)
                continue
            min_conf = info.get("min_confidence", default_conf)
            configs[epic] = StrategyConfig(epic=epic, min_confidence=min_conf)

        logger.info(
            f"Loaded optimal thresholds for {len(configs)} assets "
            f"({len(excluded)} excluded) from {thresholds_path}"
        )
        return cls(configs=configs, excluded_epics=excluded)

    def _get_config(self, epic: str) -> StrategyConfig:
        """Get or create config for an asset."""
        if epic not in self._configs:
            self._configs[epic] = StrategyConfig(epic=epic)
        return self._configs[epic]

    def process_prediction(
        self,
        prediction: PredictionResult,
        epic: str,
        market_data: dict,
    ) -> TradingSignal:
        """
        Process an ML prediction into a trading signal.

        Args:
            prediction: ML model prediction
            epic: Asset epic code
            market_data: Dict with keys:
                - current_price (float, required)
                - atr (float, required)
                - rsi (float, optional)
                - regime (str, optional)

        Returns:
            TradingSignal with direction and suggested levels
        """
        current_price = market_data.get("current_price")
        atr = market_data.get("atr")
        if current_price is None or atr is None:
            raise ValueError("market_data must contain 'current_price' and 'atr' keys")
        if not (isinstance(current_price, (int, float)) and current_price > 0):
            raise ValueError(f"Invalid current_price: {current_price}")
        if not (isinstance(atr, (int, float)) and atr > 0):
            raise ValueError(f"Invalid ATR: {atr}")

        # Mean Reversion Primary: MR rules decide direction, XGBoost scores quality
        _settings = get_settings()
        if _settings.mr_primary_enabled:
            from src.strategy.mean_reversion_strategy import MeanReversionStrategy

            mr = MeanReversionStrategy()
            mr_signal = mr.generate_signal(market_data)

            if mr_signal.direction == "HOLD":
                return TradingSignal(
                    epic=epic,
                    direction=SignalDirection.HOLD,
                    confidence=0.0,
                    signal_class=1,
                    regime=market_data.get("regime"),
                    timestamp=datetime.now(UTC),
                    technical_confirmation=False,
                    entry_price=market_data.get("current_price", 0),
                    suggested_stop=None,
                    suggested_tp=None,
                    strategy_name="mean_reversion",
                    metadata={"mr_reason": mr_signal.reason, "mr_z": mr_signal.z_score},
                )

            # XGBoost quality score: use prediction confidence as setup quality
            quality = prediction.confidence if prediction else 0.0

            # Direction from MR rules, not from XGBoost
            direction = (
                SignalDirection.BUY if mr_signal.direction == "BUY" else SignalDirection.SELL
            )

            # Apply quality gate
            if quality < _settings.mr_min_quality:
                return TradingSignal(
                    epic=epic,
                    direction=SignalDirection.HOLD,
                    confidence=quality,
                    signal_class=1,
                    regime=market_data.get("regime"),
                    timestamp=datetime.now(UTC),
                    technical_confirmation=False,
                    entry_price=market_data.get("current_price", 0),
                    suggested_stop=mr_signal.stop_level,
                    suggested_tp=mr_signal.tp_level,
                    strategy_name="mean_reversion",
                    metadata={
                        "mr_reason": f"Quality {quality:.2f} < {_settings.mr_min_quality}",
                        "mr_z": mr_signal.z_score,
                        "mr_quality": quality,
                    },
                )

            logger.info(
                f"MR-Primary [{epic}]: {mr_signal.direction} "
                f"(z={mr_signal.z_score:.2f}, quality={quality:.2f})"
            )

            return TradingSignal(
                epic=epic,
                direction=direction,
                confidence=quality,
                signal_class=2 if direction == SignalDirection.BUY else 0,
                regime=market_data.get("regime"),
                timestamp=datetime.now(UTC),
                technical_confirmation=True,
                entry_price=market_data.get("current_price", 0),
                suggested_stop=mr_signal.stop_level,
                suggested_tp=mr_signal.tp_level,
                strategy_name="mean_reversion",
                metadata={
                    "mr_z": mr_signal.z_score,
                    "mr_quality": quality,
                    "mr_direction": mr_signal.direction,
                    "mr_reason": mr_signal.reason,
                },
            )

        # Route to ORB+FVG for configured epics during NYSE hours
        if (
            self._orb_fvg_strategy is not None
            and epic in self.orb_fvg_epics
            and market_data.get("m1_bars") is not None
        ):
            return self._process_orb_fvg(epic, market_data)

        # ML-Primary mode: ML decides direction, ScalpScore confirms quality
        if self._ml_primary_enabled and self._scalp_strategy is not None:
            return self._process_ml_primary(prediction, epic, market_data)

        if self.scalp_mode and self._scalp_strategy is not None:
            return self._process_scalp(prediction, epic, market_data)

        rsi = market_data.get("rsi")
        regime = market_data.get("regime")
        adx = market_data.get("adx")

        # Get base config and adapt for regime
        base_config = self._get_config(epic)
        adapted_config = RegimeAdapter.adapt_params(regime, base_config)

        # Generate signal
        signal = SignalGenerator.generate_signal(
            prediction=prediction,
            epic=epic,
            current_price=current_price,
            atr=atr,
            rsi=rsi,
            regime=regime,
            config=adapted_config,
            adx=adx,
        )

        # Set strategy name (SignalGenerator doesn't set it)
        if signal.strategy_name is None:
            signal.strategy_name = "ml_strategy"

        logger.info(
            f"Strategy [{epic}]: {signal.direction.value} "
            f"conf={signal.confidence:.2f} regime={regime}"
        )

        return signal

    def _process_orb_fvg(
        self,
        epic: str,
        market_data: dict,
    ) -> TradingSignal:
        """Route to ORB+FVG strategy using M1 bars from market_data."""

        m1_bars = market_data["m1_bars"]
        current_price = float(market_data["current_price"])
        atr = float(market_data["atr"])

        config = StrategyConfig(
            epic=epic,
            stop_multiplier=1.0,
            risk_reward_ratio=2.0,
        )

        current_bar = {"close": current_price, "atr_14": atr}

        signal = self._orb_fvg_strategy.generate_signal(epic, current_bar, m1_bars, config)

        if signal.direction.value != "HOLD":
            logger.info(
                f"ORB+FVG [{epic}]: {signal.direction.value} " f"conf={signal.confidence:.2f}"
            )

        return signal

    def _process_scalp(
        self,
        prediction: PredictionResult,
        epic: str,
        market_data: dict,
    ) -> TradingSignal:
        """Scalp mode: technical score first, ML as boost layer."""
        from datetime import datetime

        import polars as pl

        from src.models.schemas import SignalClass
        from src.strategy.schemas import SignalDirection

        current_price = float(market_data["current_price"])
        atr = float(market_data["atr"])
        utc_hour = datetime.now(UTC).hour

        config = StrategyConfig(
            epic=epic,
            stop_multiplier=1.0,
            risk_reward_ratio=2.0,
            min_confidence=0.40,
        )

        # Build current_bar from market_data
        current_bar = {
            "close": current_price,
            "atr_14": atr,
            "rsi_14": market_data.get("rsi", 50),
            "adx_14": market_data.get("adx", 0),
            "ema_9": market_data.get("ema_9", 0),
            "ema_21": market_data.get("ema_21", 0),
            "macd_histogram": market_data.get("macd_histogram", 0),
            "macd": market_data.get("macd", 0),
            "macd_signal": market_data.get("macd_signal", 0),
            "volume": market_data.get("volume", 0),
            "volume_sma_20": market_data.get("volume_sma_20", 0),
            "bb_upper": market_data.get("bb_upper", 0),
            "bb_lower": market_data.get("bb_lower", 0),
            "bb_middle": market_data.get("bb_middle", 0),
            "keltner_upper": market_data.get("keltner_upper", 0),
            "keltner_lower": market_data.get("keltner_lower", 0),
            "vwap": market_data.get("vwap", 0),
            "utc_hour": utc_hour,
            "htf_bias": market_data.get("htf_bias"),
        }

        recent_bars = market_data.get("recent_bars", pl.DataFrame({"close": [current_price]}))

        # Step 1: Technical score signal
        signal = self._scalp_strategy.generate_signal(epic, current_bar, recent_bars, config)

        if signal.direction == SignalDirection.HOLD:
            logger.info(f"Scalp [{epic}]: HOLD (score too low)")
            return signal

        # Step 2: ML boost layer
        ml_direction = {
            SignalClass.BUY: SignalDirection.BUY,
            SignalClass.SELL: SignalDirection.SELL,
            SignalClass.HOLD: SignalDirection.HOLD,
        }.get(prediction.signal_class, SignalDirection.HOLD)

        pre_ml_confidence = signal.confidence

        if ml_direction == signal.direction and prediction.confidence > 0.40:
            # ML agrees -> full confidence (no change)
            agreement = "agree"
            logger.info(
                f"Scalp [{epic}]: {signal.direction.value} "
                f"(score->signal, ML agrees conf={prediction.confidence:.2f})"
            )
        elif ml_direction == SignalDirection.HOLD or prediction.confidence <= 0.40:
            # ML neutral -> mild reduction (×0.75), not halving.
            # Halving a 3/7 (0.43) signal to 0.21 kills it below the 0.25 floor.
            # Neutral ML means "no opinion", not "bad signal".
            agreement = "neutral"
            signal = signal.model_copy(update={"confidence": signal.confidence * 0.75})
            logger.info(
                f"Scalp [{epic}]: {signal.direction.value} "
                f"(score->signal, ML neutral -> 0.75x conf={signal.confidence:.2f})"
            )
        else:
            # ML disagrees — halve confidence but never veto
            # GURU: technical confluence is the decision maker, ML only adjusts sizing
            agreement = "disagree"
            signal = signal.model_copy(update={"confidence": signal.confidence * 0.5})
            logger.info(
                f"Scalp [{epic}]: {signal.direction.value} "
                f"(ML disagrees {ml_direction.value} conf={prediction.confidence:.2f} -> half conf={signal.confidence:.2f})"
            )

        # Add ML audit data to signal metadata
        ml_audit = {
            "signal_class": prediction.signal_class,
            "signal_name": prediction.signal_name,
            "confidence": round(prediction.confidence, 4),
            "probabilities": prediction.probabilities,
            "agreement": agreement,
            "confidence_before": round(pre_ml_confidence, 4),
            "confidence_after": round(signal.confidence, 4),
        }
        updated_metadata = {**signal.metadata, "ml": ml_audit}
        signal = signal.model_copy(
            update={"strategy_name": "scalp_score", "metadata": updated_metadata}
        )
        return signal

    def _process_ml_primary(
        self,
        prediction: PredictionResult,
        epic: str,
        market_data: dict,
    ) -> TradingSignal:
        """ML-Primary mode: ML decides direction, ScalpScore confirms quality."""
        from datetime import datetime

        import polars as pl

        from src.models.schemas import SignalClass
        from src.strategy.schemas import SignalDirection
        from src.utils.config import get_settings

        settings = get_settings()
        current_price = float(market_data["current_price"])
        atr = float(market_data["atr"])
        utc_hour = datetime.now(UTC).hour

        # Step 1: Map ML prediction to direction
        ml_direction = {
            SignalClass.BUY: SignalDirection.BUY,
            SignalClass.SELL: SignalDirection.SELL,
            SignalClass.HOLD: SignalDirection.HOLD,
        }.get(prediction.signal_class, SignalDirection.HOLD)

        # Step 2: HOLD gate
        if ml_direction == SignalDirection.HOLD:
            logger.info(f"ML-Primary [{epic}]: HOLD (ML predicts HOLD)")
            return self._make_hold(epic, current_price)

        # Step 3: Min confidence gate
        if prediction.confidence < settings.ml_primary_min_confidence:
            logger.info(
                f"ML-Primary [{epic}]: HOLD (ML conf={prediction.confidence:.2f} "
                f"< min={settings.ml_primary_min_confidence})"
            )
            return self._make_hold(epic, current_price)

        # Step 4: Build current_bar (same as _process_scalp)
        current_bar = {
            "close": current_price,
            "atr_14": atr,
            "rsi_14": market_data.get("rsi", 50),
            "adx_14": market_data.get("adx", 0),
            "ema_9": market_data.get("ema_9", 0),
            "ema_21": market_data.get("ema_21", 0),
            "macd_histogram": market_data.get("macd_histogram", 0),
            "macd": market_data.get("macd", 0),
            "macd_signal": market_data.get("macd_signal", 0),
            "volume": market_data.get("volume", 0),
            "volume_sma_20": market_data.get("volume_sma_20", 0),
            "bb_upper": market_data.get("bb_upper", 0),
            "bb_lower": market_data.get("bb_lower", 0),
            "bb_middle": market_data.get("bb_middle", 0),
            "keltner_upper": market_data.get("keltner_upper", 0),
            "keltner_lower": market_data.get("keltner_lower", 0),
            "vwap": market_data.get("vwap", 0),
            "utc_hour": utc_hour,
            "htf_bias": market_data.get("htf_bias"),
            "sil_composite_score": market_data.get("sil_composite_score", 0.0),
        }
        recent_bars = market_data.get("recent_bars", pl.DataFrame({"close": [current_price]}))

        # Step 5: Evaluate technical quality
        quality = self._scalp_strategy.evaluate_technical_quality(
            ml_direction,
            epic,
            current_bar,
            recent_bars,
        )

        # Step 6: Hard gates (session, dead market)
        if quality["session_blocked"]:
            logger.debug(f"ML-Primary [{epic}]: HOLD (session blocked)")
            return self._make_hold(epic, current_price)
        if quality["dead_market_blocked"]:
            logger.debug(f"ML-Primary [{epic}]: HOLD (dead market)")
            return self._make_hold(epic, current_price)

        # Step 7: Composite confidence
        tech_quality = quality["quality_score"]
        tech_mult = min(1.0, 0.40 + tech_quality * 0.85)
        composite = prediction.confidence * tech_mult

        if not quality["vwap_aligned"]:
            composite *= settings.ml_primary_vwap_penalty

        if quality["htf_aligned"] is False:
            composite *= settings.ml_primary_htf_penalty
        elif quality["htf_aligned"] is True:
            composite = min(1.0, composite * 1.05)

        # Step 8: Technical floor
        if tech_quality < settings.ml_primary_min_technical_quality:
            logger.info(
                f"ML-Primary [{epic}]: HOLD (tech quality {tech_quality:.2f} "
                f"< min={settings.ml_primary_min_technical_quality})"
            )
            return self._make_hold(epic, current_price)

        # Step 9: SL/TP
        config = StrategyConfig(
            epic=epic,
            stop_multiplier=1.0,
            risk_reward_ratio=2.0,
        )
        sl_mult = config.stop_multiplier
        rr = config.risk_reward_ratio
        if ml_direction == SignalDirection.BUY:
            stop = current_price - atr * sl_mult
            tp = current_price + atr * sl_mult * rr
            signal_class = SignalClass.BUY
        else:
            stop = current_price + atr * sl_mult
            tp = current_price - atr * sl_mult * rr
            signal_class = SignalClass.SELL

        # Log
        votes = quality["votes_detail"]
        votes_str = (
            f"EMA={votes.get('ema', 0):+d} RSI={votes.get('rsi', 0):+d} "
            f"MACD={votes.get('macd', 0):+d} BB={votes.get('bb', 0):+d} "
            f"VOL={votes.get('vol', 0):+d} ADX={votes.get('adx', 0):+d} "
            f"SENT={votes.get('sentiment', 0):+d}"
        )
        vwap_tag = " VWAP=opposed" if not quality["vwap_aligned"] else ""
        htf_tag = " HTF=opposed" if quality["htf_aligned"] is False else ""
        logger.info(
            f"ML-Primary [{epic}]: {ml_direction.value} "
            f"(ml_conf={prediction.confidence:.2f}, "
            f"tech={quality['agreeing_votes']}/7, "
            f"composite={composite:.2f}) "
            f"[{votes_str}]{vwap_tag}{htf_tag}"
        )

        # Step 10: Build signal
        audit_metadata = {
            "ml": {
                "signal_class": prediction.signal_class,
                "signal_name": prediction.signal_name,
                "confidence": round(prediction.confidence, 4),
                "probabilities": prediction.probabilities,
            },
            "technical_quality": {
                "agreeing_votes": quality["agreeing_votes"],
                "opposing_votes": quality["opposing_votes"],
                "quality_score": quality["quality_score"],
                "tech_multiplier": round(tech_mult, 4),
                "vwap_aligned": quality["vwap_aligned"],
                "htf_aligned": quality["htf_aligned"],
                "votes_detail": quality["votes_detail"],
            },
            "composite_confidence": round(composite, 4),
            "penalties": {
                "vwap": not quality["vwap_aligned"],
                "htf": quality["htf_aligned"] is False,
            },
        }

        return TradingSignal(
            epic=epic,
            direction=ml_direction,
            confidence=composite,
            signal_class=signal_class,
            entry_price=current_price,
            suggested_stop=stop,
            suggested_tp=tp,
            technical_confirmation=quality["agreeing_votes"] >= 3,
            strategy_name="ml_primary",
            metadata=audit_metadata,
        )

    @staticmethod
    def _make_hold(epic: str, price: float) -> TradingSignal:
        """Create a HOLD signal."""
        from src.models.schemas import SignalClass
        from src.strategy.schemas import SignalDirection

        return TradingSignal(
            epic=epic,
            direction=SignalDirection.HOLD,
            confidence=0.0,
            signal_class=SignalClass.HOLD,
            entry_price=price,
            technical_confirmation=False,
        )

    def get_allocation(self, regime: str | None = None) -> dict[str, float]:
        """
        Get portfolio allocation weights.

        Args:
            regime: Market regime for adjustment

        Returns:
            Dict of epic -> allocation weight
        """
        return PortfolioAllocator.get_allocation(regime)
